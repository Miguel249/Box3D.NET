using System;
using System.Text;

namespace Box3D.Visualizer.Rendering;

/*
 * A 5x7 bitmap font, in a byte array.
 *
 * Box3D emits labels through DrawString - a body's mass, its name, the
 * separation at a contact - and a renderer with no font has to drop them. That
 * is a real hole in the picture, and the cheapest way to close it without
 * acquiring a font dependency, a font file, or a rasterizer for outlines is the
 * one every embedded display library has used for forty years: five bytes per
 * glyph, one byte per column, one bit per row.
 *
 * The table covers the ninety-five printable ASCII characters, 0x20 to 0x7E,
 * which is everything Box3D can emit: its labels come from snprintf with %.2f,
 * %.3f, %d and a body name. Anything outside that range - a body named with an
 * accent - has no glyph, and is drawn as a question mark rather than silently
 * dropped, so a missing character looks like a missing character.
 */

/// <summary>
/// The letters, as bits.
/// </summary>
internal static class GlyphFont
{
    /// <summary>The width of a glyph in font pixels.</summary>
    public const int Width = 5;

    /// <summary>The height of a glyph in font pixels.</summary>
    public const int Height = 7;

    /// <summary>The distance from one glyph's left edge to the next, in font pixels.</summary>
    public const int Advance = Width + 1;

    /// <summary>The first character the table has a glyph for.</summary>
    public const char First = ' ';

    /// <summary>The last character the table has a glyph for.</summary>
    public const char Last = '~';

    private const char Missing = '?';

    /*
     * Five bytes per glyph, in character order from 0x20. Bit 0 of a byte is the
     * top row and bit 6 the bottom, so the columns read left to right and a
     * glyph can be blitted with a shift and a test.
     */
    private static ReadOnlySpan<byte> Table =>
    [
