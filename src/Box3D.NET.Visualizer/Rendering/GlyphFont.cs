    /// <summary>Gets how many characters the table has a glyph for.</summary>
    public static int GlyphCount => Last - First + 1;

    /// <summary>Looks up the columns of one character.</summary>
    /// <param name="character">The character.</param>
    /// <returns>
    /// Its <see cref="Width"/> columns, or those of a question mark when the
    /// table has no glyph for it.
    /// </returns>
    public static ReadOnlySpan<byte> Glyph(char character)
    {
        int index = character is >= First and <= Last ? character - First : Missing - First;

        return Table.Slice(index * Width, Width);
    }

    /// <summary>Measures a run of text.</summary>
    /// <param name="text">The text.</param>
    /// <returns>Its width in font pixels, with no trailing gap.</returns>
    public static int Measure(string text)
    {
        ArgumentNullException.ThrowIfNull(text);

        return text.Length == 0 ? 0 : (text.Length * Advance) - 1;
    }

    /// <summary>Turns the bytes Box3D handed over into characters this can draw.</summary>
    /// <param name="utf8Text">The text, UTF-8 encoded and not NUL-terminated.</param>
    /// <returns>The same text, with everything unprintable folded to a glyph that exists.</returns>
    /// <remarks>
    /// Walked byte by byte rather than decoded, because the answer for anything
    /// outside ASCII is the same question mark either way, and this way a
    /// malformed sequence cannot throw in the middle of a frame. A multi-byte
    /// sequence collapses to one question mark rather than one per byte.
    /// </remarks>
    public static string Transcribe(ReadOnlySpan<byte> utf8Text)
    {
        var text = new StringBuilder(utf8Text.Length);

        for (int i = 0; i < utf8Text.Length; i++)
        {
            byte value = utf8Text[i];

            if (value is >= (byte)First and <= (byte)Last)
            {
                text.Append((char)value);
                continue;
            }

            if (value < 0x80)
            {
                // A control character. Box3D emits none, but a body name comes
                // from the application and could hold anything.
                continue;
            }

            text.Append(Missing);

            while (i + 1 < utf8Text.Length && (utf8Text[i + 1] & 0xC0) == 0x80)
            {
                i++;
            }
        }

        return text.ToString();
    }
}
